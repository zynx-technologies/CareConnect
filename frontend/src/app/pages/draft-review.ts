import { DatePipe } from '@angular/common';
import { HttpErrorResponse } from '@angular/common/http';
import { Component, computed, inject, signal } from '@angular/core';
import { FormsModule } from '@angular/forms';
import { ActivatedRoute, Router } from '@angular/router';
import { Api, Draft, Note, Patient } from '../api';
import { PageTitle, PatientBanner } from '../ui';

@Component({
  selector: 'app-draft-review',
  imports: [DatePipe, FormsModule, PageTitle, PatientBanner],
  template: `
    <app-page-title [title]="'Discharge summary review' + (patient() ? ': ' + patient()!.givenName + ' ' + patient()!.familyName : '')" />
    @if (patient(); as p) { <app-patient-banner [patient]="p" /> }
    @if (error()) { <p class="alert" role="alert">{{ error() }}</p> }
    @if (draft(); as d) {
      <div class="cols-2">
        <section class="card">
          <h2>Source notes</h2>
          @for (n of sources(); track n.id; let i = $index) {
            <article class="src" [class.hl]="highlighted().includes(n.id)">
              <div class="kv"><span class="chip">[{{ i + 1 }}] {{ n.noteType }}, {{ n.writtenAt | date: 'd MMM' }}</span><span class="muted">{{ n.author }}</span></div>
              <p [class.mark]="highlighted().includes(n.id)">{{ n.body }}</p>
            </article>
          } @empty { <p class="muted">Loading source notes.</p> }
        </section>
        <section class="card">
          @if (d.status === 'DRAFT') {
            <h2>AI draft: not yet part of the record</h2>
            <div class="ai">
              @for (s of d.statements; track $index) {
                <p tabindex="0" (mouseenter)="highlighted.set(s.sourceIds)" (focus)="highlighted.set(s.sourceIds)"
                   (mouseleave)="highlighted.set([])" (blur)="highlighted.set([])">
                  @if (s.section) { <strong>{{ s.section }}:</strong> }
                  {{ s.text }}<span class="cite">[{{ citations(s.sourceIds) }}]</span>
                  @for (w of s.warnings; track w) { <span class="badge amber">Check: {{ w }}</span> }
                </p>
              }
            </div>
            <div class="kv"><span>Facts traced to source</span><span class="badge" [class.amber]="traced() < d.statements.length">{{ traced() }} of {{ d.statements.length }}</span></div>
            <div class="kv"><span>Items to check</span>
              @if (checks().length) { <span class="badge amber">{{ checks().length }}: {{ checks()[0] }}</span> } @else { <span class="badge">None</span> }
            </div>
            @if (checks().length > 1) { <ul class="plain">@for (c of checks().slice(1); track c) { <li><span class="badge amber">{{ c }}</span></li> }</ul> }

            <h2 class="gap">Edit and sign</h2>
            <label for="final">Final wording</label>
            <textarea id="final" rows="9" [(ngModel)]="content"></textarea>
            <label class="check"><input type="checkbox" [(ngModel)]="reviewed" /> I have reviewed this summary against the source notes.</label>
            <div class="actions-row">
              <button class="pri" [disabled]="!reviewed() || !content().trim()" (click)="sign(d)">Sign and file</button>
              <button (click)="regenerate(d)">Regenerate</button>
              <button (click)="discard(d)">Discard</button>
            </div>
            <p class="footnote">Generated by {{ d.generator }}. A clinician must review and sign before anything is filed or sent.</p>
          } @else {
            <h2>{{ d.status === 'SIGNED' ? 'Signed summary' : 'Discarded draft' }}</h2>
            <p class="pre">{{ d.content }}</p>
            @if (d.signedBy) { <p class="muted">Signed by {{ d.signedBy }}</p> }
          }
        </section>
      </div>
    }
  `,
  styles: `.gap { margin-top: 14px; } .ai p { margin: 0 0 10px; } .ai p:focus-visible { outline-offset: 4px; } .ai .badge { margin-left: 6px; }`,
})
export class DraftReviewPage {
  private api = inject(Api);
  private router = inject(Router);
  protected draft = signal<Draft | null>(null);
  protected notes = signal<Note[]>([]);
  protected patient = signal<Patient | null>(null);
  protected content = signal('');
  protected reviewed = signal(false);
  protected error = signal('');
  protected highlighted = signal<string[]>([]);

  /** Notes the draft cites, oldest first, numbered for the citations. */
  protected sources = computed(() => {
    const cited = new Set((this.draft()?.statements ?? []).flatMap((s) => s.sourceIds));
    return this.notes().filter((n) => cited.has(n.id)).sort((a, b) => a.writtenAt.localeCompare(b.writtenAt));
  });
  protected traced = computed(() => this.draft()?.tracedStatements
    ?? (this.draft()?.statements ?? []).filter((s) => s.sourceIds.length && !s.warnings.length).length);
  protected checks = computed(() => this.draft()?.itemsToCheck ?? []);

  constructor() {
    const id = inject(ActivatedRoute).snapshot.paramMap.get('id')!;
    this.api.draft(id).subscribe({
      next: (d) => {
        this.draft.set(d);
        this.content.set(d.content);
        this.api.patient(d.patientId).subscribe({
          next: (r) => { this.notes.set(r.notes); this.patient.set(r.patient ?? null); },
          error: () => this.error.set('The source notes could not be loaded, so review the record before signing.'),
        });
      },
      error: () => this.error.set('The draft could not be loaded.'),
    });
  }

  protected citations(ids: string[]): string {
    const numbers = ids.map((id) => this.sources().findIndex((n) => n.id === id) + 1).filter((n) => n > 0);
    return numbers.length ? numbers.join(', ') : 'no source';
  }

  protected sign(d: Draft): void {
    this.api.signDraft(d.id, this.content().trim(), this.reviewed()).subscribe({
      next: (signed) => this.draft.set(signed),
      error: () => this.error.set('The summary was not signed. Nothing was filed.'),
    });
  }

  protected regenerate(d: Draft): void {
    this.api.createDraft(d.patientId).subscribe({
      next: (fresh) => this.api.discardDraft(d.id).subscribe({ complete: () => window.location.assign('/drafts/' + fresh.id) }),
      error: (e: HttpErrorResponse) => this.error.set(e.status === 503
        ? 'AI drafting is turned off, so a new draft cannot be made. Edit this one or write the summary in the usual way.'
        : 'A new draft could not be made.'),
    });
  }

  protected discard(d: Draft): void {
    this.api.discardDraft(d.id).subscribe({
      next: () => void this.router.navigate(['/patients', d.patientId]),
      error: () => this.error.set('The draft could not be discarded.'),
    });
  }
}
