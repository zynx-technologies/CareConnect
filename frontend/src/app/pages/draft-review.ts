import { Component, inject, signal } from '@angular/core';
import { FormsModule } from '@angular/forms';
import { ActivatedRoute, Router } from '@angular/router';
import { Api, Draft, Note } from '../api';

@Component({
  selector: 'app-draft-review',
  imports: [FormsModule],
  template: `
    <h1>Discharge summary review</h1>
    @if (error()) { <p class="alert" role="alert">{{ error() }}</p> }
    @if (draft(); as d) {
      <div class="grid">
        <section class="card">
          <h2>Source notes</h2>
          @for (n of notes(); track n.id) {
            <article class="note"><header><strong>{{ n.noteType }}</strong> <span class="muted">{{ n.author }}</span></header><p>{{ n.body }}</p></article>
          }
        </section>
        <section class="card">
          @if (d.status === 'DRAFT') {
            <h2>AI draft: not yet part of the record</h2>
            <ul class="checks">
              @for (s of d.statements; track $index) {
                <li>{{ s.text }}
                  @for (w of s.warnings; track w) { <div class="badge amber">Check: {{ w }}</div> }
                </li>
              }
            </ul>
            <label for="final">Final wording</label>
            <textarea id="final" rows="9" [(ngModel)]="content"></textarea>
            <label class="check"><input type="checkbox" [(ngModel)]="reviewed" /> I have reviewed this summary against the source notes.</label>
            <button class="pri" [disabled]="!reviewed() || !content().trim()" (click)="sign(d)">Sign and file</button>
            <button (click)="discard(d)">Discard</button>
            <p class="muted">Generated by {{ d.generator }}. A clinician must review and sign before anything is filed.</p>
          } @else {
            <h2>{{ d.status === 'SIGNED' ? 'Signed summary' : 'Discarded draft' }}</h2>
            <p class="pre">{{ d.content }}</p>
            @if (d.signedBy) { <p class="muted">Signed by {{ d.signedBy }}</p> }
          }
        </section>
      </div>
    }
  `,
})
export class DraftReviewPage {
  private api = inject(Api);
  private router = inject(Router);
  protected draft = signal<Draft | null>(null);
  protected notes = signal<Note[]>([]);
  protected content = signal('');
  protected reviewed = signal(false);
  protected error = signal('');

  constructor() {
    const id = inject(ActivatedRoute).snapshot.paramMap.get('id')!;
    this.api.draft(id).subscribe({
      next: (d) => {
        this.draft.set(d);
        this.content.set(d.content);
        this.api.patient(d.patientId).subscribe({
          next: (r) => this.notes.set(r.notes),
          error: () => this.error.set('The source notes could not be loaded, so review the record before signing.'),
        });
      },
      error: () => this.error.set('The draft could not be loaded.'),
    });
  }

  protected sign(d: Draft): void {
    this.api.signDraft(d.id, this.content().trim(), this.reviewed()).subscribe({
      next: (signed) => this.draft.set(signed),
      error: () => this.error.set('The summary was not signed. Nothing was filed.'),
    });
  }

  protected discard(d: Draft): void {
    this.api.discardDraft(d.id).subscribe({
      next: () => void this.router.navigate(['/patients', d.patientId]),
      error: () => this.error.set('The draft could not be discarded.'),
    });
  }
}
